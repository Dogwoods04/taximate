export const LEGAL_DOC_IDS: LegalDocId[] = ['terms', 'privacy', 'location'];
export const isLegalDocId = (s: string | undefined): s is LegalDocId => !!s && (LEGAL_DOC_IDS as string[]).includes(s);
export function legalDoc(id: LegalDocId): LegalDoc {
  return id === 'privacy' ? privacy() : id === 'location' ? location() : terms();
}
export const legalTitle = (id: LegalDocId) => ({ terms: '이용약관', privacy: '개인정보 처리방침', location: '위치기반서비스 이용약관' })[id];
