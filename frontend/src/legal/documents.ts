const v = (value: string, label: string) => value.trim() || `〔미정: ${label}〕`;

export function operatorFacts() {
  const contact = [OPERATOR.email.trim(), OPERATOR.phone.trim()].filter(Boolean).join(' · ');
  return {
    name: v(OPERATOR.name, '운영자명'),
    address: v(OPERATOR.address, '주소'),
    email: v(OPERATOR.email, '문의 이메일'),
    phone: OPERATOR.phone.trim() || '없음(이메일로 문의)',
    contact: contact || '〔미정: 문의 이메일〕',
    privacyOfficer: v(OPERATOR.privacyOfficer, '개인정보 보호책임자'),
    privacyOfficerContact: OPERATOR.privacyOfficerContact.trim() || contact || '〔미정: 보호책임자 연락처〕',
    locationOfficer: OPERATOR.locationOfficer.trim() || v(OPERATOR.privacyOfficer, '위치정보관리책임자'),
    effective: LEGAL_EFFECTIVE_DATE || '〔미정: 시행일〕',
    version: LEGAL_VERSION,
  };
}

